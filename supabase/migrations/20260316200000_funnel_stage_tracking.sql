    ('workshop_attendee', 'Workshop Attendee', 10),
    ('community_member', 'Community Member', 20),
    ('ai_consultant', 'AI Consultant', 30),
    ('coaching_client', 'Coaching Client', 40);

-- Stage history - tracks every transition with timestamp
CREATE TABLE IF NOT EXISTS contact_stage_history (
    id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    contact_id bigint NOT NULL REFERENCES contacts(id) ON DELETE CASCADE,
    from_stage text,
    to_stage text NOT NULL,
    changed_at timestamp with time zone DEFAULT now(),
    changed_by uuid REFERENCES auth.users(id),
    notes text,
    sales_id bigint,
    created_at timestamp with time zone DEFAULT now()
);

CREATE INDEX idx_stage_history_contact ON contact_stage_history(contact_id);
CREATE INDEX idx_stage_history_changed_at ON contact_stage_history(changed_at);

-- Add funnel_stage column to contacts if not exists
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'contacts' AND column_name = 'funnel_stage') THEN
        ALTER TABLE contacts ADD COLUMN funnel_stage text DEFAULT 'lead';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name = 'contacts' AND column_name = 'funnel_stage_changed_at') THEN
        ALTER TABLE contacts ADD COLUMN funnel_stage_changed_at timestamp with time zone DEFAULT now();
    END IF;
END $$;


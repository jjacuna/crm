-- Auto-set sales_id trigger for contact_stage_history (follow existing pattern)
CREATE TRIGGER set_contact_stage_history_sales_id_trigger
    BEFORE INSERT ON contact_stage_history
    FOR EACH ROW
    EXECUTE FUNCTION set_sales_id_default();

-- Trigger to auto-log stage changes when funnel_stage is updated on contacts
CREATE OR REPLACE FUNCTION handle_contact_stage_change()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.funnel_stage IS DISTINCT FROM NEW.funnel_stage THEN
        INSERT INTO contact_stage_history (contact_id, from_stage, to_stage, changed_by)
        VALUES (NEW.id, OLD.funnel_stage, NEW.funnel_stage, auth.uid());
        NEW.funnel_stage_changed_at = now();
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_contact_funnel_stage_change
    BEFORE UPDATE ON contacts
    FOR EACH ROW
    EXECUTE FUNCTION handle_contact_stage_change();

-- Update contacts_summary view to include funnel_stage and funnel_stage_changed_at
drop view if exists contacts_summary;

create view contacts_summary
as
select
    co.*,
    jsonb_path_query_array(co.email_jsonb, '$[*].email')::text as email_fts,
    jsonb_path_query_array(co.phone_jsonb, '$[*].number')::text as phone_fts,
    c.name as company_name,
    count(distinct t.id) filter (where t.done_date is null) as nb_tasks
from
    contacts co
left join
    tasks t on co.id = t.contact_id
left join
    companies c on co.company_id = c.id
group by
    co.id, c.name;
